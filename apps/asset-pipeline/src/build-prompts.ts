/**
 * Generates the input glyphs from Kenney's CC0 Input Prompts (https://kenney.nl):
 *
 *   npm run prompts -w @frontier/asset-pipeline -- --source "<Input Prompts>"
 *
 * Picks the keyboard/mouse, Xbox and PlayStation glyphs the HUD needs, tints them with
 * `currentColor` (so CSS colours them) and writes them inline into
 * `apps/client/src/ui/input-prompts.ts` (generated; ~10 KB, no extra requests).
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { parseArgs } from 'node:util';

/** Glyph name → file inside the pack. Names are what the client asks for. */
export const PROMPTS = {
  'kb-mouse-left': 'Keyboard & Mouse/Vector/mouse_left.svg',
  'kb-mouse-right': 'Keyboard & Mouse/Vector/mouse_right.svg',
  'kb-q': 'Keyboard & Mouse/Vector/keyboard_q.svg',
  'kb-space': 'Keyboard & Mouse/Vector/keyboard_space.svg',
  'kb-tab': 'Keyboard & Mouse/Vector/keyboard_tab.svg',
  'kb-shift': 'Keyboard & Mouse/Vector/keyboard_shift.svg',
  'kb-m': 'Keyboard & Mouse/Vector/keyboard_m.svg',
  'kb-escape': 'Keyboard & Mouse/Vector/keyboard_escape.svg',
  'xbox-a': 'Xbox Series/Vector/xbox_button_color_a.svg',
  'xbox-b': 'Xbox Series/Vector/xbox_button_color_b.svg',
  'xbox-x': 'Xbox Series/Vector/xbox_button_color_x.svg',
  'xbox-y': 'Xbox Series/Vector/xbox_button_color_y.svg',
  'xbox-rb': 'Xbox Series/Vector/xbox_rb.svg',
  'xbox-r3': 'Xbox Series/Vector/xbox_stick_r_press.svg',
  'xbox-view': 'Xbox Series/Vector/xbox_button_view.svg',
  'xbox-menu': 'Xbox Series/Vector/xbox_button_menu.svg',
  'ps-cross': 'PlayStation Series/Vector/playstation_button_color_cross.svg',
  'ps-circle': 'PlayStation Series/Vector/playstation_button_color_circle.svg',
  'ps-square': 'PlayStation Series/Vector/playstation_button_color_square.svg',
  'ps-triangle': 'PlayStation Series/Vector/playstation_button_color_triangle.svg',
  'ps-r1': 'PlayStation Series/Vector/playstation_trigger_r1.svg',
  'ps-r3': 'PlayStation Series/Vector/playstation_stick_r_press.svg',
} as const;

const { values } = parseArgs({
  options: {
    source: { type: 'string' },
    out: { type: 'string', default: path.resolve(import.meta.dirname, '../../client/src/ui/input-prompts.ts') },
  },
});
if (!values.source) throw new Error('Pass --source "<Input Prompts pack folder>"');

const entries: string[] = [];
for (const [name, file] of Object.entries(PROMPTS)) {
  const svg = await readFile(path.join(values.source, file), 'utf8');
  const inner = svg
    .replace(/<\?xml[^>]*>/, '')
    .replace(/<svg[^>]*>/, '')
    .replace(/<\/svg>\s*$/, '')
    .replace(/<defs\/>/g, '')
    .replace(/\s*\n\s*/g, '')
    .replace(/fill="#(?:FFFFFF|ffffff|FFF|fff)"/g, 'fill="currentColor"')
    .replace(/ stroke="none"/g, '')
    .trim();
  if (!/^<g>.*<\/g>$/.test(inner) && !inner.startsWith('<path')) console.warn(`${name}: unexpected markup, kept as-is`);
  entries.push(`  '${name}': '${inner.replace(/'/g, "\\'")}',`);
}

await writeFile(
  values.out!,
  `// Generated by apps/asset-pipeline/src/build-prompts.ts from Kenney's Input Prompts (CC0,
// https://kenney.nl). Do not edit by hand. Each entry is the inner markup of a 64×64 SVG; white
// parts use currentColor so CSS can tint them.
export const INPUT_PROMPTS = {
${entries.join('\n')}
} as const;

export type PromptName = keyof typeof INPUT_PROMPTS;

/** Full SVG markup for one glyph. */
export function promptSvg(name: PromptName, size = 24): string {
  return \`<svg xmlns="http://www.w3.org/2000/svg" width="\${size}" height="\${size}" viewBox="0 0 64 64" aria-hidden="true">\${INPUT_PROMPTS[name]}</svg>\`;
}
`,
);
console.log(`Wrote ${values.out} (${Object.keys(PROMPTS).length} glyphs)`);
